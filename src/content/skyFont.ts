/** Lit dots per character as [column, row] (row 0 at the top). */
export const SKY_FONT: Record<string, [number, number][]> = Object.fromEntries(
  Object.entries(GLYPHS).map(([ch, rows]) => [
    ch,
    rows
      .split(' ')
      .flatMap((row, y) => [...row].flatMap((c, x) => (c === '#' ? [[x, y] as [number, number]] : []))),
  ]),
);

/** Longest message the sky can hold (characters, spaces included). */
export const SKY_TEXT_MAX = 18;

/**
 * Cleans a message for the sky: upper case, `<3` and hearts become ♥, characters the font lacks are dropped,
 * spaces collapse, and it is cut to SKY_TEXT_MAX. Returns '' when nothing is left.
 */
export function skyText(raw: string): string {
  const s = raw
    .toUpperCase()
    .replace(/<3|[❤♡💖💕💗]/gu, '♥')
    .replace(/[‘’]/g, "'");
  const kept = [...s].filter((c) => c === ' ' || SKY_FONT[c]).join('');
  return kept.replace(/\s+/g, ' ').trim().slice(0, SKY_TEXT_MAX).trim();
}
